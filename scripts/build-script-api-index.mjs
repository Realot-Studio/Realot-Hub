#!/usr/bin/env node
/**
 * Generates project/editor/mcp/script-api-index.js from the real script API
 * (project/runtime/scripting/ScriptAPI.js) so get_script_api / search_docs /
 * validate_script always match the engine. Run after changing ScriptAPI.js:
 *   node scripts/build-script-api-index.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "project/runtime/scripting/ScriptAPI.js"), "utf8").split("\n");

// The globals object is the `return { ... };` that contains `findFirst: function`.
const anchor = src.findIndex((l) => /^\s{6}findFirst: function \(name\)/.test(l));
if (anchor < 0) throw new Error("Could not find the script globals block in ScriptAPI.js");
let start = anchor; while (start > 0 && !/^\s{4}return \{\s*$/.test(src[start])) start--;
let end = anchor; while (end < src.length && !/^\s{4}\};\s*$/.test(src[end])) end++;

const docBefore = (i) => {
  // Collect the comment block directly above line i (/** */ or // lines).
  let j = i - 1; const out = [];
  if (/^\s*\*\/\s*$/.test(src[j] || "")) {
    j--; while (j >= 0 && !/^\s*\/\*\*/.test(src[j])) { out.unshift(src[j].replace(/^\s*\* ?/, "")); j--; }
  } else {
    while (j >= 0 && /^\s*\/\/ ?/.test(src[j])) { out.unshift(src[j].replace(/^\s*\/\/ ?/, "")); j--; }
  }
  const text = out.join("\n").trim();
  const para = text.split(/\n\s*\n/)[0].replace(/\s*\n\s*/g, " ").trim();
  return para.slice(0, 600);
};

const globals = {};
let current = null;
for (let i = start + 1; i < end; i++) {
  const l = src[i];
  let m;
  if ((m = l.match(/^ {6}(\w+): function \(([^)]*)\)/))) {
    globals[m[1]] = { kind: "function", signature: `${m[1]}(${m[2].trim()})`, doc: docBefore(i), members: {} };
    current = null;
  } else if ((m = l.match(/^ {6}(\w+): \{\s*$/)) || (m = l.match(/^ {6}(\w+): (?:new Proxy|createSaveAPI|self\.)/))) {
    globals[m[1]] = { kind: "object", doc: docBefore(i), members: {} };
    current = m[1];
  } else if ((m = l.match(/^ {6}(\w+): /))) {
    globals[m[1]] = { kind: "value", doc: docBefore(i), members: {} };
    current = null;
  } else if (current && (m = l.match(/^ {8}(\w+): function \(([^)]*)\)/))) {
    globals[current].members[m[1]] = { signature: `${current}.${m[1]}(${m[2].trim()})`, doc: docBefore(i) };
  } else if (current && (m = l.match(/^ {8}get (\w+)\(\)/))) {
    globals[current].members[m[1]] = { signature: `${current}.${m[1]}  (property)`, doc: docBefore(i) };
  } else if (current && (m = l.match(/^ {8}(\w+)\(([^)]*)\) \{/))) {
    globals[current].members[m[1]] = { signature: `${current}.${m[1]}(${m[2].trim()})`, doc: docBefore(i) };
  }
}

// Entity-context members (this.x, this.destroy(), ...) are documented in the guide.
const out = { generatedFrom: "project/runtime/scripting/ScriptAPI.js", globals };
const target = join(root, "project/editor/mcp/script-api-index.js");
writeFileSync(target, "// GENERATED by scripts/build-script-api-index.mjs — do not edit by hand.\nexport default " + JSON.stringify(out, null, 1) + ";\n");
const n = Object.keys(globals).length;
const members = Object.values(globals).reduce((s, g) => s + Object.keys(g.members).length, 0);
console.log(`Wrote ${target}: ${n} globals, ${members} members`);
